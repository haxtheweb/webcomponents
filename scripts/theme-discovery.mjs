#!/usr/bin/env node

/**
 * HAXcms Theme Discovery Script
 *
 * This script discovers all HAXcms themes in the webcomponents repository
 * by looking for classes that extend HAXCMSLitElementTheme and generates
 * a theme registry JSON file compatible with the HAXcms-php themes.json format.
 *
 * The script will output to elements/haxcms-elements/lib/themes.json
 */

import fs from "fs";
import path from "path";
import { promisify } from "util";
import globCallback from "glob";
const glob = promisify(globCallback);

// Tags that should never surface as user-facing categories
const BANNED_TAGS = new Set(["Blank", "Personal", "Module"]);

// Thumbnail paths using bare import style that can be resolved by basePath
// Screenshots will be generated by the Puppeteer automation after themes.json is created
function generateThumbnailPath(elementName) {
  return `@haxtheweb/haxcms-elements/lib/theme-screenshots/theme-${elementName}-thumb.jpg`;
}

/**
 * Extract the theme name from a filename or class name
 */
function extractThemeName(content, filename) {
  // Look for static get tag() methods FIRST (most reliable)
  const tagMatch = content.match(
    /static\s+get\s+tag\(\)\s*{\s*return\s+['"`]([a-z][a-z0-9-]*)['"`]/,
  );
  if (tagMatch) {
    return tagMatch[1];
  }

  // Look for customElements.define calls
  const defineMatch = content.match(
    /customElements\.define\(['"`]([a-z][a-z0-9-]*)['"`]/,
  );
  if (defineMatch) {
    return defineMatch[1];
  }

  // Look for explicit theme name in comments or JSDoc (less reliable)
  const nameMatch = content.match(/@element\s+([a-z][a-z0-9-]*)/);
  if (nameMatch) {
    return nameMatch[1];
  }

  // Fallback to filename
  const baseName = path.basename(filename, ".js");
  return baseName;
}

/**
 * Extract display name from content or generate from element name
 */
function extractDisplayName(content, elementName) {
  // Look for JSDoc description or title
  const titleMatch = content.match(/@title\s+([^\n]+)/i);
  if (titleMatch) {
    return titleMatch[1].trim();
  }

  // Look for short description in comments (limit to reasonable length)
  const descMatch = content.match(/`([^`]{1,100}theme[^`]{0,20})`/i);
  if (descMatch) {
    return descMatch[1];
  }

  // Look for class name comments (with length limits)
  const classMatch = content.match(/\/\*\*\s*\n\s*\*\s*([^\n]{1,100})\s*\n/);
  if (classMatch && classMatch[1].toLowerCase().includes("theme")) {
    return classMatch[1];
  }

  // Generate Title Case from element name (dash-case to Title Case)
  // Example: "clean-portfolio-theme" -> "Clean Portfolio Theme"
  return elementName
    .split("-")
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1).toLowerCase())
    .join(" ");
}

/**
 * Generate description for blank use case from theme name
 */
function generateBlankDescription(displayName) {
  return `Start with a blank site using the ${displayName}`;
}

/**
 * Determine if a theme should be hidden from user selection
 * These are system or debugging themes that shouldn't appear in use case dashboard
 */
function shouldHideTheme(elementName) {
  const hiddenThemes = [
    "haxcms-json-theme",
    "haxcms-blank-theme",
    "haxcms-print-theme",
  ];
  return hiddenThemes.includes(elementName);
}

/**
 * Extract a boolean tag from a JSDoc block.
 *
 * Supports either:
 * - @tag true|false
 * - @tag  (implies true)
 */
function extractBooleanDocblockTag(content, tagName) {
  const tagMatch = content.match(
    new RegExp(`@${tagName}(?:\\s+(true|false))?`, "i"),
  );
  if (tagMatch) {
    if (typeof tagMatch[1] === "string") {
      return tagMatch[1].toLowerCase() === "true";
    }
    return true;
  }
  return null;
}

/**
 * Extract a numeric tag from a JSDoc block.
 *
 * Supports:
 * - @tag -10
 * - @tag 0
 * - @tag 100
 */
function extractNumericDocblockTag(content, tagName) {
  const tagMatch = content.match(
    new RegExp(`@${tagName}\\s+(-?\\d+(?:\\.\\d+)?)`, "i"),
  );
  if (tagMatch && typeof tagMatch[1] !== "undefined") {
    const num = Number(tagMatch[1]);
    return Number.isFinite(num) ? num : null;
  }
  return null;
}

/**
 * Determine if a theme is a terrible theme (intentionally bad design)
 */
function extractThemeTerrible(content, elementName) {
  // Docblock override
  const terrible = extractBooleanDocblockTag(content, "haxcms-theme-terrible");
  if (terrible !== null) {
    return terrible;
  }
  // Fallback: infer from name
  return elementName.includes("terrible");
}

/**
 * Generate thumbnail path for a theme (will be created by Puppeteer automation)
 */
function getThumbnailPath(elementName) {
  return generateThumbnailPath(elementName);
}

/**
 * Extract theme categories from JSDoc or infer from element name.
 * Ensures we never emit banned tags like "Blank", "Personal", or "Module".
 */
function extractThemeCategories(content, elementName) {
  // 1. Docblock override: @haxcms-theme-category Course, Website
  const catMatch = content.match(/@haxcms-theme-category\s+([^\n]+)/i);
  if (catMatch) {
    return catMatch[1]
      .split(",")
      .map((t) => t.trim())
      .filter((t) => t && !BANNED_TAGS.has(t));
  }

  return ["Website"];
}

/**
 * Determine if a theme should be hidden from selection based on JSDoc.
 * Hidden themes stay in themes.json but are not shown in the v2 picker.
 */
function extractThemePriority(content) {
  const priority = extractNumericDocblockTag(content, "haxcms-theme-priority");
  return priority !== null ? priority : 0;
}

/**
 * Extract supported palette numbers from a JSDoc block.
 * Supports comma-separated values: @haxcms-theme-palettes 0, 4, 5, 8
 */
function extractThemePalettes(content) {
  const match = content.match(/@haxcms-theme-palettes\s+([^\n]+)/i);
  if (match) {
    return match[1]
      .split(",")
      .map((s) => s.trim())
      .filter((s) => s !== "");
  }
  return null;
}

function extractThemeHidden(content, elementName) {
  // Prefer explicit hidden flag
  const hidden = extractBooleanDocblockTag(content, "haxcms-theme-hidden");
  if (hidden !== null) {
    return hidden;
  }

  // Backwards compatible alias: internal => hidden
  const internal = extractBooleanDocblockTag(content, "haxcms-theme-internal");
  if (internal !== null) {
    return internal;
  }

  return shouldHideTheme(elementName);
}

/**
 * Extract a single-line text value from a JSDoc tag, e.g.
 * @haxcms-theme-layout Sidebar
 */
function extractTextDocblockTag(content, tagName) {
  const match = content.match(new RegExp(`@${tagName}[ \\t]+([^\\n*]+)`, "i"));
  if (match) {
    const value = match[1].trim();
    return value !== "" ? value : null;
  }
  return null;
}

/**
 * Whether this file's class says it can take another design system:
 * static get acceptsDesignSystems() { return true; }
 */
function declaresAcceptsDesignSystems(content) {
  return /static\s+get\s+acceptsDesignSystems\s*\(\s*\)\s*\{\s*return\s+true\b/.test(
    content,
  );
}

/**
 * One themes.json entry. Browsing facets come from docblock tags on the
 * theme's own file:
 *   @haxcms-theme-category      what it is for (comma separated)
 *   @haxcms-theme-layout        Sidebar, Top nav or Single column
 *   @haxcms-theme-design-system the system it is built on, when not DDD
 *   @haxcms-theme-inspired-by   the project it is an homage to (Jekyll,
 *                               Hugo, Astro...), the browsing group
 *   @haxcms-theme-inspired-by-theme  that project's theme, when there is one
 *   @haxcms-theme-description   one sentence shown when picking a theme
 */
function buildThemeEntry(content, file, elementName) {
  const displayName = extractDisplayName(content, elementName);
  return {
    element: elementName,
    path: generateNpmPath(file),
    name: displayName,
    thumbnail: getThumbnailPath(elementName),
    description:
      extractTextDocblockTag(content, "haxcms-theme-description") ||
      generateBlankDescription(displayName),
    category: extractThemeCategories(content, elementName),
    hidden: extractThemeHidden(content, elementName),
    priority: extractThemePriority(content),
    terrible: extractThemeTerrible(content, elementName),
    supportedPalettes: extractThemePalettes(content),
    layout: extractTextDocblockTag(content, "haxcms-theme-layout"),
    designSystem: extractTextDocblockTag(content, "haxcms-theme-design-system"),
    inspiredBy: extractTextDocblockTag(content, "haxcms-theme-inspired-by"),
    inspiredByTheme: extractTextDocblockTag(
      content,
      "haxcms-theme-inspired-by-theme",
    ),
    // filled in after discovery, following the class chain
    acceptsDesignSystems: false,
  };
}

/**
 * Generate the NPM path for the theme
 */
function generateNpmPath(filePath) {
  // Convert file path to NPM path format
  // keep the file's real location: themes nested below lib/ (haxcms-elements
  // keeps its built-in themes in lib/core/themes/) must not be flattened to
  // lib/<tag>.js, a file that does not exist
  const relativePath = filePath.replace("./elements/", "");
  return `@haxtheweb/${relativePath}`;
}

/**
 * Check if file contains direct HAXCMSLitElementTheme extension
 */
function isDirectHAXcmsTheme(content) {
  // a class that extends HAXCMSLitElementTheme, directly or through mixins
  // such as DDDSuper(...); a file that only mentions the name (in a comment,
  // an import it re-exports) is not a theme
  return /class\s+\w+\s+extends\s+[\w(\s,]*\bHAXCMSLitElementTheme\b/.test(
    content,
  );
}

/**
 * Extract the class name that this theme extends
 */
function getExtendedClassName(content) {
  // Look for 'extends ClassName' pattern
  const extendMatch = content.match(/class\s+\w+\s+extends\s+([\w()]+)/);
  if (extendMatch) {
    // Handle patterns like DDDSuper(HAXCMSLitElementTheme) by extracting the base class
    const extendedClass = extendMatch[1];
    if (extendedClass.includes("(") && extendedClass.includes(")")) {
      const innerMatch = extendedClass.match(/\(([^)]+)\)/);
      return innerMatch ? innerMatch[1] : extendedClass;
    }
    return extendedClass;
  }
  return null;
}

/**
 * Check if file extends a known theme class
 */
function extendsThemeClass(content, knownThemeClasses) {
  const extendedClass = getExtendedClassName(content);
  return extendedClass && knownThemeClasses.has(extendedClass);
}

/**
 * Check whether a name is a structurally valid custom element tag name
 * (lowercase, hyphenated, e.g. "my-element"). Themes are always real,
 * registered custom elements, so anything that isn't a valid custom
 * element name (e.g. a bare class/file name like "HAXCMSThemeWiring")
 * cannot actually be a theme and should be ignored, even if the file
 * otherwise looks like it references theme base classes (for example
 * via a comment mentioning "HAXCMSLitElementTheme").
 */
function isValidCustomElementName(name) {
  return /^[a-z][a-z0-9]*(-[a-z0-9]+)+$/.test(name);
}

/**
 * Check if a theme should be skipped based on exclusion rules
 */
function shouldSkipTheme(elementName, filePath) {
  // Exclude specific theme names (not real themes or base classes)
  const excludedNames = [
    "AppHaxStore",
    "custom.es6",
    "custom-journey-theme",
    "HAXCMSLitElementTheme", // Base class, not a theme
    "haxcms-basic-theme", // Internal basic theme
    "haxcms-slide-theme", // Internal slide theme
    "haxcms-dev-theme", // Development theme
    "simple-colors-shared-styles", // Shared styles, not a theme
  ];
  if (excludedNames.includes(elementName)) {
    return true;
  }

  // Exclude themes with 'example' in the file path
  if (filePath.includes("example")) {
    return true;
  }

  // Exclude test files - any file with '.test' in the name
  if (filePath.includes(".test") || elementName.includes(".test")) {
    return true;
  }

  // Exclude anything that isn't a valid custom element tag name. A real
  // theme is always a registered custom element (e.g. "clean-two"); things
  // like mixin/wiring classes (e.g. "HAXCMSThemeWiring") get picked up by
  // the naive content matching above but aren't actual themes.
  if (!isValidCustomElementName(elementName)) {
    return true;
  }

  return false;
}

/**
 * Main theme discovery function with multi-pass inheritance detection
 */
/**
 * Whether this run also writes themes.json into sibling haxcms-nodejs and
 * haxcms-php checkouts (../haxcms-nodejs, ../haxcms-php). Only the release
 * build asks for it (gulp theme-discovery, part of yarn ubiquity), so a
 * contributor registering a theme never touches other repos by accident.
 */
function shouldSyncPlatforms(argv = [], env = {}) {
  return (
    argv.indexOf("--sync-platforms") !== -1 ||
    env.HAX_THEME_SYNC_PLATFORMS === "1"
  );
}

/**
 * themes.json as the repo keeps it: Prettier's JSON format (short arrays on
 * one line), so a run only shows the entries that changed. Plain
 * JSON.stringify when Prettier is not installed.
 */
async function formatThemesJson(themes, filePath) {
  const text = JSON.stringify(themes, null, 2);
  try {
    const prettier = await import("prettier");
    const config = (await prettier.resolveConfig(filePath)) || {};
    return await prettier.format(text, { ...config, parser: "json" });
  } catch {
    return text + "\n";
  }
}

async function discoverThemes(options = {}) {
  const syncPlatforms = !!options.syncPlatforms;
  console.log("🔍 Discovering HAXcms themes...");

  const themes = {};
  const knownThemeClasses = new Set(["HAXCMSLitElementTheme"]);
  const fileContentMap = new Map();

  try {
    // Find all JavaScript files in elements directory
    const files = await glob("./elements/**/*.js", {
      ignore: [
        "./elements/**/demo/**",
        "./elements/**/test/**",
        "./elements/**/node_modules/**",
        "./elements/**/lib/**/*.haxProperties.json",
        "./elements/**/*.test.js",
      ],
    });

    console.log(`📁 Scanning ${files.length} JavaScript files...`);

    // First pass: Load all file contents and find direct HAXcms themes

    for (const file of files) {
      try {
        const content = fs.readFileSync(file, "utf8");
        fileContentMap.set(file, content);

        // Check if this file contains a direct HAXcms theme
        if (isDirectHAXcmsTheme(content)) {
          const elementName = extractThemeName(content, file);

          // Track the class even when the file is not a theme itself: base
          // classes such as HomageThemeBase are what real themes extend
          const classMatch = content.match(/class\s+(\w+)\s+extends/);
          if (classMatch) {
            knownThemeClasses.add(classMatch[1]);
          }

          // Skip excluded themes
          if (shouldSkipTheme(elementName, file)) {
            continue;
          }

          themes[elementName] = buildThemeEntry(content, file, elementName);
        }
      } catch (error) {
        console.warn(`⚠️  Error processing file ${file}: ${error.message}`);
      }
    }

    // Multi-pass inheritance detection: keep looking for themes that extend discovered themes
    let passNumber = 2;
    let foundNewThemes = true;

    while (foundNewThemes) {
      foundNewThemes = false;

      for (const [file, content] of fileContentMap) {
        const elementName = extractThemeName(content, file);
        if (
          themes[elementName] ||
          !extendsThemeClass(content, knownThemeClasses)
        ) {
          continue;
        }

        // Track intermediate base classes (HomageSidebarTheme, ...) even
        // though they are not themes themselves
        const classMatch = content.match(/class\s+(\w+)\s+extends/);
        if (classMatch && !knownThemeClasses.has(classMatch[1])) {
          knownThemeClasses.add(classMatch[1]);
          foundNewThemes = true;
        }

        if (shouldSkipTheme(elementName, file)) {
          continue;
        }

        themes[elementName] = buildThemeEntry(content, file, elementName);
        foundNewThemes = true;
      }

      passNumber++;

      // Safety check to prevent infinite loops
      if (passNumber > 10) {
        console.warn(
          "⚠️  Stopped inheritance detection after 10 passes to prevent infinite loops",
        );
        break;
      }
    }

    // acceptsDesignSystems is inherited: a theme accepts one when its own
    // class or any class it extends declares it (the homage themes get it
    // from HomageThemeBase)
    const classInfo = new Map();
    const themeClass = new Map();
    for (const [file, content] of fileContentMap) {
      const classMatch = content.match(/class\s+(\w+)\s+extends/);
      if (!classMatch) continue;
      classInfo.set(classMatch[1], {
        parent: getExtendedClassName(content),
        accepts: declaresAcceptsDesignSystems(content),
      });
      const tag = extractThemeName(content, file);
      if (themes[tag] && !themeClass.has(tag))
        themeClass.set(tag, classMatch[1]);
    }
    const accepts = (className, depth) => {
      const info = classInfo.get(className);
      if (!info || depth > 10) return false;
      return info.accepts || accepts(info.parent, depth + 1);
    };
    for (const [tag, className] of themeClass) {
      themes[tag].acceptsDesignSystems = accepts(className, 0);
    }

    console.log(`🎨 Discovered ${Object.keys(themes).length} themes`);

    // Sort themes alphabetically by element name (case-insensitive)
    const sortedThemes = Object.keys(themes)
      .sort((a, b) => a.localeCompare(b))
      .reduce((sorted, key) => {
        sorted[key] = themes[key];
        return sorted;
      }, {});

    // Ensure output directory exists
    const outputDir = "./elements/haxcms-elements/lib";
    if (!fs.existsSync(outputDir)) {
      fs.mkdirSync(outputDir, { recursive: true });
    }

    // Write themes.json file
    const outputPath = path.join(outputDir, "themes.json");
    const output = await formatThemesJson(sortedThemes, outputPath);
    fs.writeFileSync(outputPath, output);

    console.log(`📄 Theme registry written to: ${outputPath}`);

    if (!syncPlatforms) {
      console.log(
        "ℹ️  Not syncing to ../haxcms-nodejs or ../haxcms-php (the release build does that with --sync-platforms)",
      );
      console.log("🎉 Theme discovery completed successfully!");
      return themes;
    }

    // release build: sync themes.json to both HAXcms platforms using relative paths
    try {
      const nodejsPath = "../haxcms-nodejs/src/coreConfig/themes.json";
      const phpPath = "../haxcms-php/system/coreConfig/themes.json";

      // Copy to Node.js platform
      fs.writeFileSync(nodejsPath, output);
      console.log(`🔄 Synced themes.json to HAXcms Node.js: ${nodejsPath}`);

      // Copy to PHP platform
      fs.writeFileSync(phpPath, output);
      console.log(`🔄 Synced themes.json to HAXcms PHP: ${phpPath}`);
    } catch (syncError) {
      console.warn(
        `⚠️  Warning: Could not sync themes.json to platforms: ${syncError.message}`,
      );
    }

    console.log("🎉 Theme discovery and platform sync completed successfully!");

    return themes;
  } catch (error) {
    console.error("❌ Error during theme discovery:", error);
    process.exit(1);
  }
}

// Run the script if called directly
if (import.meta.url === `file://${process.argv[1]}`) {
  discoverThemes({
    syncPlatforms: shouldSyncPlatforms(process.argv.slice(2), process.env),
  }).catch((error) => {
    console.error("❌ Fatal error:", error);
    process.exit(1);
  });
}

export default discoverThemes;
export {
  shouldSyncPlatforms,
  formatThemesJson,
  isDirectHAXcmsTheme,
  declaresAcceptsDesignSystems,
  extractTextDocblockTag,
  buildThemeEntry,
};
