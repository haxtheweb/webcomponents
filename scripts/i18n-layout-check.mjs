#!/usr/bin/env node
/**
 * i18n layout check: pseudo-localization and right-to-left rendering of
 * HAX-capable elements.
 *
 * Invariant: a HAX-capable element keeps a usable layout when its strings
 * get longer (translations run ~30-40% longer than English) and when it is
 * placed in a right-to-left language (Arabic, Hebrew, Persian, Urdu...).
 * Translation files cannot show this; rendering can.
 *
 * Which tags: custom element tags in hax-elements-registry.json whose class
 * carries a HAXSchema (haxProperties on the class or an ancestor, or a
 * setHaxProperties(schema, "<tag>") call), the same set the API snapshot
 * gate covers. Each one is rendered from its first demoSchema entry in
 * Chromium (web-test-runner) and compared with its English left-to-right
 * render; see scripts/test-setup/i18n-layout-runner.js for the checks.
 * Physical-direction CSS (rtl-css) is a static scan of the tag's css``
 * templates (scripts/lib/i18n-layout.mjs).
 *
 * Baseline: scripts/i18n-layout.baseline.json lists today's failures per tag
 * and check. Only a check failing for a tag that has no baseline entry for
 * it is new. By default only tags whose element folder changed are checked,
 * so pre-existing problems elsewhere never block a pull request; they are
 * listed as advisory output to be worked down.
 *
 *   yarn test:i18n-layout                   tags in element folders changed vs the base branch
 *   yarn test:i18n-layout --base <ref>      compare with another ref (CI passes HEAD^1)
 *   yarn test:i18n-layout --tags a-b,c-d    only these tags
 *   yarn test:i18n-layout --all             every HAX-capable tag
 *   yarn test:i18n-layout:baseline          re-run every tag and rewrite the baseline
 *   yarn test:i18n-layout:baseline --tags a-b   refresh only these tags in the baseline
 *
 * Exit 1 when a checked tag has a new failure, 0 otherwise.
 */
import { spawnSync } from "node:child_process";
import console from "node:console";
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import {
  ADVISORY_CHECKS,
  CHECKS,
  changedFiles,
  changedFolders,
  compareToBaseline,
  listTagEntries,
  rtlCssForTag,
} from "./lib/i18n-layout.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const BASELINE = path.join(root, "scripts", "i18n-layout.baseline.json");
const OUT = path.join(root, ".cache", "i18n-layout");
const WTR_CONFIG = path.join(
  root,
  "scripts",
  "test-setup",
  "i18n-layout.wtr.config.mjs",
);
const BATCH = Number(process.env.I18N_LAYOUT_BATCH) || 12;
const LIST_LIMIT = 8;
// changes to the check itself re-check every tag
const TOOLING = [
  /^scripts\/i18n-layout/,
  /^scripts\/lib\/i18n-layout\.mjs$/,
  /^scripts\/lib\/pseudo-locale\.mjs$/,
  /^scripts\/lib\/css-templates\.mjs$/,
  /^scripts\/test-setup\/i18n-layout/,
  /^\.github\/workflows\/i18n-layout\.yml$/,
];

const argv = process.argv.slice(2);
const flag = (name) => argv.includes(name);
const option = (name) => {
  const i = argv.indexOf(name);
  return i !== -1 && argv[i + 1] && !argv[i + 1].startsWith("--")
    ? argv[i + 1]
    : null;
};
const UPDATE = flag("--update-baseline") || flag("--baseline");
const ALL = flag("--all");
const TAGS = option("--tags");

function findBase() {
  const candidates = ["origin/HEAD", "origin/master", "origin/main"];
  return candidates.find(
    (ref) =>
      spawnSync("git", ["rev-parse", "--verify", "--quiet", ref], {
        cwd: root,
      }).status === 0,
  );
}

function readBaseline() {
  try {
    const data = JSON.parse(fs.readFileSync(BASELINE, "utf8"));
    return data.tags || {};
  } catch {
    return {};
  }
}

function writeBaseline(tags) {
  const sorted = {};
  for (const tag of Object.keys(tags).sort()) {
    const checks = {};
    for (const check of Object.keys(tags[tag]).sort()) {
      checks[check] = tags[tag][check];
    }
    if (Object.keys(checks).length) {
      sorted[tag] = checks;
    }
  }
  const data = {
    about:
      "Known i18n layout failures: tag -> check -> number of findings. Generated by yarn test:i18n-layout:baseline; do not edit by hand. See CONTRIBUTING.md (i18n layout check).",
    tags: sorted,
  };
  fs.writeFileSync(BASELINE, JSON.stringify(data, null, 2) + "\n");
}

/** pick the tags to check and say why */
function selectEntries(entries) {
  if (TAGS) {
    const want = new Set(TAGS.split(",").map((t) => t.trim()));
    return {
      picked: entries.filter((e) => want.has(e.tag)),
      why: `--tags (${want.size})`,
    };
  }
  if (ALL || UPDATE) {
    return { picked: entries, why: "all tags" };
  }
  const base = option("--base") || findBase();
  const files = changedFiles(root, base);
  if (files.some((f) => TOOLING.some((re) => re.test(f)))) {
    return { picked: entries, why: "the check itself changed: all tags" };
  }
  const folders = changedFolders(files);
  return {
    picked: entries.filter((e) => folders.has(e.folder)),
    why: `element folders changed vs ${base || "local changes"}: ${[...folders].sort().join(", ") || "none"}`,
  };
}

function runBrowser(picked) {
  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(path.join(OUT, "results"), { recursive: true });
  let n = 0;
  for (let i = 0; i < picked.length; i += BATCH) {
    n += 1;
    const entries = picked
      .slice(i, i + BATCH)
      .map(({ tag, module, setHax }) => ({ tag, module, setHax }));
    const body = [
      "// generated by scripts/i18n-layout-check.mjs",
      'import { runBatch } from "/scripts/test-setup/i18n-layout-runner.js";',
      `const entries = ${JSON.stringify(entries)};`,
      `describe("i18n layout batch ${n}", () => {`,
      `  it("measures ${entries.map((e) => e.tag).join(", ")}", async () => {`,
      "    await runBatch(entries);",
      "  });",
      "});",
      "",
    ].join("\n");
    fs.writeFileSync(
      path.join(OUT, `batch-${String(n).padStart(3, "0")}.test.js`),
      body,
    );
  }
  const bin = path.join(
    root,
    "node_modules",
    "@web",
    "test-runner",
    "dist",
    "bin.js",
  );
  console.log(
    `i18n-layout: rendering ${picked.length} tag(s) in ${n} batch(es) (Chromium)`,
  );
  const res = spawnSync(
    process.execPath,
    [bin, "--config", WTR_CONFIG, "--static-logging"],
    {
      cwd: root,
      stdio: ["ignore", "inherit", "inherit"],
      env: { ...process.env, I18N_LAYOUT_DIR: OUT },
    },
  );
  if (res.status !== 0) {
    console.log(
      "i18n-layout: the browser run reported errors; tags without results are listed as render errors",
    );
  }
  const results = {};
  for (const { tag } of picked) {
    const file = path.join(OUT, "results", `${tag}.json`);
    try {
      results[tag] = JSON.parse(fs.readFileSync(file, "utf8"));
    } catch {
      results[tag] = {
        renderError: "no result (test page crashed or timed out)",
      };
    }
  }
  return results;
}

function line(text) {
  console.log(text);
  return text;
}

function main() {
  const entries = listTagEntries(root);
  const { picked, why } = selectEntries(entries);
  console.log(`i18n-layout: ${why}`);
  if (!picked.length) {
    console.log("i18n-layout: no HAX-capable tags to check.");
    return 0;
  }
  const raw = runBrowser(picked);
  // gating results per tag: runtime checks + static rtl-css
  const results = {};
  const hardcoded = {};
  const renderErrors = {};
  const rtlIgnored = {};
  let notHax = 0;
  for (const entry of picked) {
    const r = raw[entry.tag] || {};
    if (r.notHaxCapable) {
      notHax += 1;
      continue;
    }
    if (r.renderError) {
      renderErrors[entry.tag] = r.renderError;
    }
    const checks = { ...(r.checks || {}) };
    if (checks.hardcoded) {
      hardcoded[entry.tag] = checks.hardcoded;
    }
    if (checks["rtl-ignored"]) {
      rtlIgnored[entry.tag] = checks["rtl-ignored"][0];
    }
    Object.keys(ADVISORY_CHECKS).forEach((c) => delete checks[c]);
    const rtlCss = rtlCssForTag(root, entry);
    if (rtlCss.length) {
      checks["rtl-css"] = rtlCss;
    }
    results[entry.tag] = checks;
  }
  const checked = Object.keys(results).length;
  const gating = Object.keys(CHECKS);
  const summary = [];

  if (UPDATE) {
    const baseline = TAGS ? readBaseline() : {};
    for (const tag of Object.keys(results)) {
      const counts = {};
      for (const check of gating) {
        if (results[tag][check] && results[tag][check].length) {
          counts[check] = results[tag][check].length;
        }
      }
      baseline[tag] = counts;
    }
    writeBaseline(baseline);
    printCounts(results, gating);
    console.log(
      `i18n-layout: baseline written for ${checked} HAX-capable tag(s) (${notHax} registry tag(s) without a HAXSchema skipped).`,
    );
    return 0;
  }

  const baseline = readBaseline();
  const { fresh, known, fixed } = compareToBaseline(results, baseline, gating);
  if (known.length) {
    summary.push(
      line(
        `\nAdvisory: ${known.length} baselined failure(s) in the checked tags (work these down, then refresh the baseline):`,
      ),
    );
    for (const k of known) {
      summary.push(line(`  ${k.tag}  ${k.check}  (${k.details.length})`));
      k.details
        .slice(0, LIST_LIMIT)
        .forEach((d) => summary.push(line(`      ${d}`)));
      if (k.details.length > LIST_LIMIT) {
        summary.push(
          line(`      ...and ${k.details.length - LIST_LIMIT} more`),
        );
      }
    }
  }
  const hcTags = Object.keys(hardcoded);
  if (hcTags.length) {
    summary.push(
      line(
        `\nAdvisory: visible shadow-DOM text without pseudo-locale markers in ${hcTags.length} tag(s) (hard-coded string candidates; move them into this.t):`,
      ),
    );
    for (const tag of hcTags) {
      const list = hardcoded[tag];
      summary.push(
        line(
          `  ${tag}: ${list
            .slice(0, LIST_LIMIT)
            .map((s) => JSON.stringify(s))
            .join(
              ", ",
            )}${list.length > LIST_LIMIT ? ` ...+${list.length - LIST_LIMIT}` : ""}`,
        ),
      );
    }
  }
  const ignTags = Object.keys(rtlIgnored);
  if (ignTags.length) {
    summary.push(
      line(
        `\nAdvisory: dir="rtl" on the content column did not reach ${ignTags.length} tag(s):`,
      ),
    );
    ignTags.forEach((t) => summary.push(line(`  ${t}: ${rtlIgnored[t]}`)));
  }
  const errTags = Object.keys(renderErrors);
  if (errTags.length) {
    summary.push(
      line(
        `\nAdvisory: ${errTags.length} tag(s) did not render in the test page:`,
      ),
    );
    errTags.forEach((t) => summary.push(line(`  ${t}: ${renderErrors[t]}`)));
  }
  if (fixed.length) {
    summary.push(
      line(
        `\nFixed since the baseline (run yarn test:i18n-layout:baseline --tags ${[...new Set(fixed.map((f) => f.tag))].join(",")} to drop them):`,
      ),
    );
    fixed.forEach((f) => summary.push(line(`  ${f.tag}  ${f.check}`)));
  }
  if (fresh.length) {
    summary.push(line(`\nNEW i18n layout failures (${fresh.length}):`));
    for (const f of fresh) {
      summary.push(line(`  ${f.tag}  ${f.check}: ${CHECKS[f.check]}`));
      f.details
        .slice(0, LIST_LIMIT)
        .forEach((d) => summary.push(line(`      ${d}`)));
      if (f.details.length > LIST_LIMIT) {
        summary.push(
          line(`      ...and ${f.details.length - LIST_LIMIT} more`),
        );
      }
    }
  }
  summary.push(
    line(
      `\ni18n-layout: ${checked} HAX-capable tag(s) checked, ${fresh.length} new failure(s), ${known.length} baselined, ${fixed.length} fixed.`,
    ),
  );
  if (process.env.GITHUB_STEP_SUMMARY) {
    try {
      fs.appendFileSync(
        process.env.GITHUB_STEP_SUMMARY,
        `## i18n layout (pseudo-locale + RTL)\n\n\`\`\`\n${summary.join("\n").trim()}\n\`\`\`\n`,
      );
    } catch {
      // the summary is a convenience
    }
  }
  return fresh.length ? 1 : 0;
}

function printCounts(results, gating) {
  const counts = {};
  gating.forEach((c) => (counts[c] = 0));
  for (const tag of Object.keys(results)) {
    for (const check of gating) {
      if (results[tag][check] && results[tag][check].length) {
        counts[check] += 1;
      }
    }
  }
  console.log("i18n-layout: tags failing each check:");
  gating.forEach((c) => console.log(`  ${c}: ${counts[c]}`));
}

// mention the advisory checks so --help style readers find them
if (flag("--help")) {
  console.log("Checks (gating):");
  Object.keys(CHECKS).forEach((c) => console.log(`  ${c}: ${CHECKS[c]}`));
  console.log("Advisory:");
  Object.keys(ADVISORY_CHECKS).forEach((c) =>
    console.log(`  ${c}: ${ADVISORY_CHECKS[c]}`),
  );
  process.exit(0);
}
process.exit(main());
