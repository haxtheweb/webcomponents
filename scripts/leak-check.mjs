#!/usr/bin/env node
/**
 * Memory-leak check for HAX-capable elements.
 *
 * Invariant: removing a HAX-capable element from the page releases what it
 * set up. Attaching and detaching it again and again must not leave growing
 * global listeners, observers, intervals or animation-frame loops behind,
 * must not grow globalThis stores, and the removed instances must be
 * garbage-collectable. Pages built in HAX add and remove elements constantly
 * (editing, previews, the outline designer, theme switches), so a leak per
 * instance adds up over a session.
 *
 * Which tags: custom element tags in hax-elements-registry.json whose class
 * carries a HAXSchema (haxProperties on the class or an ancestor, or a
 * setHaxProperties(schema, "<tag>") call), the same set the API snapshot
 * gate covers. Each one is built from its first demoSchema entry in Chromium
 * (web-test-runner), attached, awaited and removed 2 warm-up times and then
 * LEAK_CHECK_CYCLES (default 12) measured times; see
 * scripts/test-setup/leak-runner.js. Only what grew with at least half of
 * the measured cycles is a leak, so singletons and per-tag registrations
 * never count.
 *
 * Baseline: scripts/leak-check.baseline.json lists today's leaks per tag and
 * check. Only a check failing for a tag that has no baseline entry for it is
 * new. By default only tags whose element folder changed are checked, so
 * pre-existing leaks elsewhere never block a pull request; they are listed as
 * advisory output to be worked down.
 *
 *   yarn test:leaks                   tags in element folders changed vs the base branch
 *   yarn test:leaks --base <ref>      compare with another ref (CI passes HEAD^1)
 *   yarn test:leaks --tags a-b,c-d    only these tags
 *   yarn test:leaks --all             every HAX-capable tag
 *   yarn test:leaks:baseline          re-run every tag and rewrite the baseline
 *   yarn test:leaks:baseline --tags a-b   refresh only these tags in the baseline
 *   yarn test:leaks --self-test       prove the check still finds each kind of
 *                                     leak (scripts/test-setup/leak-fixtures.js)
 *
 * Exit 1 when a checked tag has a new leak, 0 otherwise.
 */
import { spawnSync } from "node:child_process";
import console from "node:console";
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import {
  ADVISORY_CHECKS,
  CHECKS,
  changedFiles,
  changedFolders,
  compareToBaseline,
  listTagEntries,
  SHARED_LEAKS,
  sharedLeaksOf,
  toChecks,
} from "./lib/leak-check.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const BASELINE = path.join(root, "scripts", "leak-check.baseline.json");
const OUT = path.join(root, ".cache", "leak-check");
const WTR_CONFIG = path.join(
  root,
  "scripts",
  "test-setup",
  "leak.wtr.config.mjs",
);
const BATCH = Number(process.env.LEAK_CHECK_BATCH) || 10;
const CYCLES = Math.max(4, Number(process.env.LEAK_CHECK_CYCLES) || 12);
const LIST_LIMIT = 6;
// changes to the check itself re-check every tag
const TOOLING = [
  /^scripts\/leak-check/,
  /^scripts\/lib\/leak-check\.mjs$/,
  /^scripts\/test-setup\/leak/,
  /^\.github\/workflows\/leak-check\.yml$/,
];

const argv = process.argv.slice(2);
const flag = (name) => argv.includes(name);
const option = (name) => {
  const i = argv.indexOf(name);
  return i !== -1 && argv[i + 1] && !argv[i + 1].startsWith("--")
    ? argv[i + 1]
    : null;
};
const UPDATE = flag("--update-baseline") || flag("--baseline");
const ALL = flag("--all");
const TAGS = option("--tags");

function findBase() {
  const candidates = ["origin/HEAD", "origin/master", "origin/main"];
  return candidates.find(
    (ref) =>
      spawnSync("git", ["rev-parse", "--verify", "--quiet", ref], {
        cwd: root,
      }).status === 0,
  );
}

function readBaseline() {
  try {
    const data = JSON.parse(fs.readFileSync(BASELINE, "utf8"));
    return data.tags || {};
  } catch {
    return {};
  }
}

function writeBaseline(tags) {
  const sorted = {};
  for (const tag of Object.keys(tags).sort()) {
    const checks = {};
    for (const check of Object.keys(tags[tag]).sort()) {
      checks[check] = tags[tag][check];
    }
    if (Object.keys(checks).length) {
      sorted[tag] = checks;
    }
  }
  const data = {
    about:
      "Known memory leaks: tag -> check -> number of findings. Generated by yarn test:leaks:baseline; do not edit by hand. See CONTRIBUTING.md (Memory-leak check).",
    tags: sorted,
  };
  fs.writeFileSync(BASELINE, JSON.stringify(data, null, 2) + "\n");
}

/** pick the tags to check and say why */
function selectEntries(entries) {
  if (TAGS) {
    const want = new Set(TAGS.split(",").map((t) => t.trim()));
    return {
      picked: entries.filter((e) => want.has(e.tag)),
      why: `--tags (${want.size})`,
    };
  }
  if (ALL || UPDATE) {
    return { picked: entries, why: "all tags" };
  }
  const base = option("--base") || findBase();
  const files = changedFiles(root, base);
  if (files.some((f) => TOOLING.some((re) => re.test(f)))) {
    return { picked: entries, why: "the check itself changed: all tags" };
  }
  const folders = changedFolders(files);
  return {
    picked: entries.filter((e) => folders.has(e.folder)),
    why: `element folders changed vs ${base || "local changes"}: ${[...folders].sort().join(", ") || "none"}`,
  };
}

function runBrowser(picked, batchSize = BATCH) {
  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(path.join(OUT, "results"), { recursive: true });
  let n = 0;
  for (let i = 0; i < picked.length; i += batchSize) {
    n += 1;
    const entries = picked
      .slice(i, i + batchSize)
      .map(({ tag, module, setHax }) => ({ tag, module, setHax }));
    const body = [
      "// generated by scripts/leak-check.mjs",
      'import { runBatch } from "/scripts/test-setup/leak-runner.js";',
      `const entries = ${JSON.stringify(entries)};`,
      `describe("leak check batch ${n}", () => {`,
      `  it("cycles ${entries.map((e) => e.tag).join(", ")}", async () => {`,
      `    await runBatch(entries, { cycles: ${CYCLES} });`,
      "  });",
      "});",
      "",
    ].join("\n");
    fs.writeFileSync(
      path.join(OUT, `batch-${String(n).padStart(3, "0")}.test.js`),
      body,
    );
  }
  const bin = path.join(
    root,
    "node_modules",
    "@web",
    "test-runner",
    "dist",
    "bin.js",
  );
  console.log(
    `leak-check: cycling ${picked.length} tag(s) ${CYCLES}x in ${n} batch(es) (Chromium)`,
  );
  const res = spawnSync(
    process.execPath,
    [bin, "--config", WTR_CONFIG, "--static-logging"],
    {
      cwd: root,
      stdio: ["ignore", "inherit", "inherit"],
      env: { ...process.env, LEAK_CHECK_DIR: OUT },
    },
  );
  if (res.status !== 0) {
    console.log(
      "leak-check: the browser run reported errors; tags without results are listed as render errors",
    );
  }
  const results = {};
  for (const { tag } of picked) {
    const file = path.join(OUT, "results", `${tag}.json`);
    try {
      results[tag] = JSON.parse(fs.readFileSync(file, "utf8"));
    } catch {
      results[tag] = {
        renderError: "no result (test page crashed or timed out)",
      };
    }
  }
  return results;
}

function line(text) {
  console.log(text);
  return text;
}

function listDetails(summary, details) {
  details.slice(0, LIST_LIMIT).forEach((d) => summary.push(line(`      ${d}`)));
  if (details.length > LIST_LIMIT) {
    summary.push(line(`      ...and ${details.length - LIST_LIMIT} more`));
  }
}

function printCounts(results, gating) {
  const counts = {};
  gating.forEach((c) => (counts[c] = 0));
  for (const tag of Object.keys(results)) {
    for (const check of gating) {
      if (results[tag][check] && results[tag][check].length) {
        counts[check] += 1;
      }
    }
  }
  console.log("leak-check: tags failing each check:");
  gating.forEach((c) => console.log(`  ${c}: ${counts[c]}`));
}

const FIXTURES = "scripts/test-setup/leak-fixtures.js";

/** the fixtures must give exactly these results */
function selfTest() {
  const raw = runBrowser([
    { tag: "leak-fixture-clean", module: FIXTURES, setHax: false },
    { tag: "leak-fixture-leaky", module: FIXTURES, setHax: false },
  ]);
  const clean = toChecks(raw["leak-fixture-clean"] || {}, CYCLES);
  const leaky = toChecks(raw["leak-fixture-leaky"] || {}, CYCLES);
  const problems = [];
  ["leak-fixture-clean", "leak-fixture-leaky"].forEach((tag) => {
    if (raw[tag] && raw[tag].renderError) {
      problems.push(`${tag} did not render: ${raw[tag].renderError}`);
    }
  });
  Object.keys(clean).forEach((check) =>
    problems.push(
      `leak-fixture-clean reported ${check}: ${clean[check].join("; ")}`,
    ),
  );
  Object.keys(CHECKS).forEach((check) => {
    if (!leaky[check]) {
      problems.push(`leak-fixture-leaky: ${check} was not detected`);
    }
  });
  problems.forEach((p) => console.log(`  ${p}`));
  console.log(
    problems.length
      ? "leak-check self-test: FAILED"
      : `leak-check self-test: every check found the leaky fixture and none blamed the clean one (${CYCLES} cycles)`,
  );
  return problems.length ? 1 : 0;
}

function main() {
  if (flag("--self-test")) {
    return selfTest();
  }
  const entries = listTagEntries(root);
  const { picked, why } = selectEntries(entries);
  console.log(`leak-check: ${why}`);
  if (!picked.length) {
    console.log("leak-check: no HAX-capable tags to check.");
    return 0;
  }
  const raw = runBrowser(picked);
  const results = {};
  const renderErrors = {};
  let notHax = 0;
  let noGc = false;
  const shared = {};
  for (const entry of picked) {
    const r = raw[entry.tag] || {};
    if (r.notHaxCapable) {
      notHax += 1;
      continue;
    }
    if (r.renderError) {
      renderErrors[entry.tag] = r.renderError;
      results[entry.tag] = {};
      continue;
    }
    if (r.gc === false) {
      noGc = true;
    }
    results[entry.tag] = toChecks(r, CYCLES);
    sharedLeaksOf(r, CYCLES).forEach((p) => {
      shared[p] = shared[p] || [];
      shared[p].push(entry.tag);
    });
  }
  if (noGc) {
    console.log(
      "leak-check: globalThis.gc was not exposed; garbage collection went through the DevTools protocol",
    );
  }
  const checked = Object.keys(results).length;
  const gating = Object.keys(CHECKS);
  const summary = [];

  if (UPDATE) {
    // What is already loaded in the page changes what a tag leaves behind,
    // and a pull request run checks only a few tags. So the baseline is the
    // union of the batched run and a run with every tag alone in its page.
    console.log("leak-check: second pass, one tag per page");
    const alone = runBrowser(
      picked.filter((e) => results[e.tag]),
      1,
    );
    for (const tag of Object.keys(results)) {
      const r = alone[tag] || {};
      if (r.renderError || r.notHaxCapable) {
        continue;
      }
      const more = toChecks(r, CYCLES);
      for (const check of Object.keys(more)) {
        const now = results[tag][check] || [];
        results[tag][check] =
          now.length >= more[check].length ? now : more[check];
      }
    }
    const baseline = TAGS ? readBaseline() : {};
    for (const tag of Object.keys(results)) {
      const counts = {};
      for (const check of gating) {
        if (results[tag][check] && results[tag][check].length) {
          counts[check] = results[tag][check].length;
        }
      }
      baseline[tag] = counts;
    }
    writeBaseline(baseline);
    printCounts(results, gating);
    Object.keys(shared).forEach((p) =>
      console.log(
        `  shared (advisory, not in the baseline): globalThis.${p} in ${shared[p].length} tag(s)`,
      ),
    );
    console.log(
      `leak-check: baseline written for ${checked} HAX-capable tag(s) (${notHax} registry tag(s) without a HAXSchema skipped, ${Object.keys(renderErrors).length} did not render).`,
    );
    return 0;
  }

  const baseline = readBaseline();
  const first = compareToBaseline(results, baseline, gating);
  const { known, fixed } = first;
  let { fresh } = first;
  if (fresh.length) {
    // Garbage collection and async work make a single run noisy, and which
    // tags shared the page changes what is already loaded. A new leak only
    // counts when a second run of just those tags, in a fresh page, sees it
    // again.
    const again = [...new Set(fresh.map((f) => f.tag))];
    console.log(
      `leak-check: confirming ${fresh.length} new leak(s) with a second run of ${again.join(", ")}`,
    );
    const rerun = runBrowser(picked.filter((e) => again.includes(e.tag)));
    const unconfirmed = [];
    fresh = fresh.filter((f) => {
      const r = rerun[f.tag] || {};
      const checks = r.renderError ? {} : toChecks(r, CYCLES);
      const seen = Boolean(checks[f.check] && checks[f.check].length);
      if (!seen) {
        unconfirmed.push(f);
      }
      return seen;
    });
    if (unconfirmed.length) {
      summary.push(
        line(
          `\nAdvisory: ${unconfirmed.length} leak(s) seen once but not on the second run (timing; not gated):`,
        ),
      );
      unconfirmed.forEach((f) => summary.push(line(`  ${f.tag}  ${f.check}`)));
    }
  }
  if (known.length) {
    summary.push(
      line(
        `\nAdvisory: ${known.length} baselined leak(s) in the checked tags (work these down, then refresh the baseline):`,
      ),
    );
    for (const k of known) {
      summary.push(line(`  ${k.tag}  ${k.check}`));
      listDetails(summary, k.details);
    }
  }
  Object.keys(shared).forEach((p) => {
    summary.push(
      line(
        `\nAdvisory: shared leak in ${shared[p].length} checked tag(s), not gated (${SHARED_LEAKS[p]}): globalThis.${p}`,
      ),
    );
    summary.push(line(`  ${shared[p].join(", ")}`));
  });
  const errTags = Object.keys(renderErrors);
  if (errTags.length) {
    summary.push(
      line(
        `\nAdvisory: ${errTags.length} tag(s) did not render in the test page (${ADVISORY_CHECKS["render-error"]}):`,
      ),
    );
    errTags.forEach((t) => summary.push(line(`  ${t}: ${renderErrors[t]}`)));
  }
  if (fixed.length) {
    summary.push(
      line(
        `\nFixed since the baseline (run yarn test:leaks:baseline --tags ${[...new Set(fixed.map((f) => f.tag))].join(",")} to drop them):`,
      ),
    );
    fixed.forEach((f) => summary.push(line(`  ${f.tag}  ${f.check}`)));
  }
  if (fresh.length) {
    summary.push(line(`\nNEW memory leaks (${fresh.length}):`));
    for (const f of fresh) {
      summary.push(line(`  ${f.tag}  ${f.check}: ${CHECKS[f.check]}`));
      listDetails(summary, f.details);
    }
  }
  summary.push(
    line(
      `\nleak-check: ${checked} HAX-capable tag(s) checked (${CYCLES} cycles each), ${fresh.length} new leak(s), ${known.length} baselined, ${fixed.length} fixed.`,
    ),
  );
  if (process.env.GITHUB_STEP_SUMMARY) {
    try {
      fs.appendFileSync(
        process.env.GITHUB_STEP_SUMMARY,
        `## Memory leaks (attach/detach cycles)\n\n\`\`\`\n${summary.join("\n").trim()}\n\`\`\`\n`,
      );
    } catch {
      // the summary is a convenience
    }
  }
  return fresh.length ? 1 : 0;
}

if (flag("--help")) {
  console.log("Checks (gating):");
  Object.keys(CHECKS).forEach((c) => console.log(`  ${c}: ${CHECKS[c]}`));
  console.log("Advisory:");
  Object.keys(ADVISORY_CHECKS).forEach((c) =>
    console.log(`  ${c}: ${ADVISORY_CHECKS[c]}`),
  );
  process.exit(0);
}
process.exit(main());
