// node --test scripts/test/*.test.mjs
import process from "node:process";
import { test } from "node:test";
import assert from "node:assert/strict";
import { classify, inScope } from "../license-header-check.mjs";

test("only element source files are in scope", () => {
  assert.ok(inScope("elements/my-el/my-el.js"));
  assert.ok(inScope("elements/my-el/lib/my-el-item.js"));
  assert.ok(inScope("elements/my-el/lib/sub/deep.js"));
  for (const f of [
    "elements/my-el/test/my-el.test.js",
    "elements/my-el/demo/demo.js",
    "elements/my-el/locales/my-el.en.json",
    "elements/my-el/lib/my-el.haxProperties.json",
    "elements/my-el/lib/vendor/thing.js",
    "elements/my-el/lib/lib-x/dist/x.js",
    "elements/my-el/lib/x.min.js",
    "elements/my-el/my-el.stories.js",
    "elements/my-el/rollup.config.js",
    "elements/my-el/gulpfile.js",
    "elements/my-el/gulpfile.cjs",
    "elements/my-el/node_modules/a/index.js",
    "elements/my-el/build.mjs",
    "scripts/new-script.mjs",
    "elements/top.js",
  ]) {
    assert.equal(inScope(f), false, f);
  }
});

test("the header hax webcomponent scaffolds passes", () => {
  assert.equal(
    classify(`/**
 * Copyright 2026 btopro
 * @license Apache-2.0, see LICENSE for full text.
 */
import { LitElement } from "lit";
`),
    "ok",
  );
  assert.equal(
    classify(`#!/usr/bin/env node
/**
 * Copyright 2019 The Pennsylvania State University
 * @license Apache-2.0, see License.md for full text.
 */
`),
    "ok",
  );
});

test("missing, empty or partial headers fail", () => {
  assert.equal(classify(`import { LitElement } from "lit";\n`), "missing");
  assert.equal(
    classify(`/**\n * @license , see License.md for full text.\n */\n`),
    "missing",
  );
  assert.equal(
    classify(`/**\n * @license Apache-2.0, see License.md.\n */\n`),
    "missing",
  );
  assert.equal(classify(`/**\n * Copyright 2026 me\n */\n`), "missing");
  // a header further down the file does not count
  assert.equal(
    classify(
      `import x from "y";\n/**\n * Copyright 2026 me\n * @license Apache-2.0\n */\n`,
    ),
    "missing",
  );
});

test("generated and vendored files carry their own headers", () => {
  assert.equal(
    classify(
      `// generated by scripts/x.mjs; do not edit.\nexport const A = 1;\n`,
    ),
    "generated",
  );
  assert.equal(
    classify(`/*! lib v1.2.3 | (c) Someone | MIT License */\n!function(){}`),
    "third-party",
  );
  assert.equal(
    classify(`/**\n * Copyright 2020 Someone\n * @license MIT\n */\n`),
    "third-party",
  );
});

test("third-party code is listed by path, and only those paths are skipped", async () => {
  const { isThirdParty } = await import("../license-header-check.mjs");
  assert.ok(isThirdParty("elements/utils/lib/marked.js"));
  assert.ok(isThirdParty("elements/code-sample/lib/highlightjs/languages/css.js"));
  assert.equal(isThirdParty("elements/utils/utils.js"), false);
  assert.equal(isThirdParty("elements/code-sample/code-sample.js"), false);
});

test("every element source file carries the header (--all)", async () => {
  const { execFileSync } = await import("node:child_process");
  const { fileURLToPath } = await import("node:url");
  const script = fileURLToPath(
    new URL("../license-header-check.mjs", import.meta.url),
  );
  // throws (exit 1) when any first-party file lacks the header
  execFileSync(process.execPath, [script, "--all"], { stdio: "pipe" });
});
