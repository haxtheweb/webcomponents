#!/usr/bin/env node
/**
 * Block review per design system, written into each bridged theme's README.
 *
 * Reads scripts/contrast.design-systems.baseline.json (what the
 * contrast-design-systems workflow knows still fails under each bridge) and
 * lists, per system, how many HAX blocks pass color contrast in light and
 * dark and which are baselined (by mode, with node counts). The section sits
 * between <!-- block-review --> and <!-- /block-review --> in
 * elements/<theme>/README.md and is replaced on every run.
 *
 *   node scripts/design-system-report.mjs           write the READMEs
 *   node scripts/design-system-report.mjs --check   exit 1 if one is stale
 */
import console from "node:console";
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { demoElements } from "./lib/demo-runner.mjs";
import { isHaxBlock, listDesignSystems } from "./lib/design-systems.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const BASELINE = path.join(
  root,
  "scripts/contrast.design-systems.baseline.json",
);
const START = "<!-- block-review -->";
const END = "<!-- /block-review -->";

let systems = {};
try {
  systems = JSON.parse(fs.readFileSync(BASELINE, "utf8")).systems || {};
} catch {
  systems = {};
}
const blocks = demoElements(root).filter((e) => isHaxBlock(root, e));

function nodes(modeMap) {
  return Object.values(modeMap).reduce((n, count) => n + count, 0);
}

function section(system) {
  const known = systems[system.name] || {};
  const failing = Object.keys(known).sort();
  const lines = [
    START,
    "## Block review",
    "",
    `Every HAX block's demo is measured with ${system.title} active, in light and dark mode, by the \`contrast-design-systems\` workflow (axe-core color contrast, WCAG AA). Generated by \`node scripts/design-system-report.mjs\` from \`scripts/contrast.design-systems.baseline.json\`; see CONTRIBUTING.md, "Color contrast check".`,
    "",
    `**${blocks.length - failing.length} of ${blocks.length}** HAX blocks pass in light and dark.`,
  ];
  if (failing.length) {
    lines.push(
      "",
      "Baselined (known failures to work down; nothing new may be added):",
      "",
      "| Block | Mode | Nodes |",
      "| --- | --- | --- |",
    );
    failing.forEach((element) => {
      Object.keys(known[element])
        .sort()
        .forEach((mode) => {
          lines.push(
            `| ${element} | ${mode} | ${nodes(known[element][mode])} |`,
          );
        });
    });
  }
  lines.push(END);
  return lines.join("\n");
}

let stale = 0;
for (const system of listDesignSystems(root)) {
  const readme = path.join(root, "elements", system.element, "README.md");
  if (!fs.existsSync(readme)) {
    continue;
  }
  const text = fs.readFileSync(readme, "utf8");
  const body = section(system);
  const next =
    text.includes(START) && text.includes(END)
      ? text.slice(0, text.indexOf(START)) +
        body +
        text.slice(text.indexOf(END) + END.length)
      : `${text.trimEnd()}\n\n${body}\n`;
  if (next !== text) {
    if (process.argv.includes("--check")) {
      console.error(`stale: ${path.relative(root, readme)}`);
      stale++;
    } else {
      fs.writeFileSync(readme, next);
      console.log(`wrote ${path.relative(root, readme)}`);
    }
  }
}
process.exit(stale ? 1 : 0);
