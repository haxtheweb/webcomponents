#!/usr/bin/env node
/**
 * HAXSchema gate: the HAX editing schema (haxProperties) of every HAX-capable
 * element a pull request touches is valid and matches the element.
 *
 * Invariant: an authorable element's HAXSchema validates against the HAX
 * properties JSON Schema (scripts/lib/haxProperties.schema.json, from
 * https://github.com/haxtheweb/hax-schema), every settings field edits a
 * property, attribute or slot the element really declares, and every
 * demoSchema entry inserts the element's own tag; or the problem is already
 * listed in scripts/haxschema.baseline.json. The baseline only shrinks.
 *
 * Which tags, and what the element declares, come from the API snapshot
 * gate (scripts/api-snapshot.mjs): tags in hax-elements-registry.json whose
 * class carries a HAXSchema (static get haxProperties(), own or inherited,
 * or setHaxProperties(schema, "<tag>")), with attributes, Lit properties and
 * slots read by the custom elements manifest analyzer in memory. The checks
 * themselves are in scripts/lib/haxschema.mjs; the baseline mechanics in
 * scripts/lib/gate-baseline.mjs are the contrast gate's.
 *
 *   yarn test:haxschema                     tags in element folders changed vs the base branch
 *   yarn test:haxschema --base <ref>        compare with another ref (CI passes HEAD^1)
 *   yarn test:haxschema --tags a-b,c-d      only these tags
 *   yarn test:haxschema --all               every authorable tag
 *   yarn test:haxschema --update-baseline   drop what is fixed (only removes)
 *   yarn test:haxschema --update-baseline --allow-additions   only add (CI fails a baseline that grew)
 *   yarn test:haxschema --check-baseline <ref>   fail if the baseline grew compared with <ref>
 *
 * The static read is the same everywhere, so every tag is analyzed (about
 * 20 seconds) and only the selected ones gate. Exit 1 on a new problem in a
 * selected tag (or a grown baseline), 0 otherwise.
 */
import { execFileSync } from "node:child_process";
import console from "node:console";
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { buildSnapshot, loadAnalyzer } from "./api-snapshot.mjs";
import { changedFiles, changedFolders } from "./lib/i18n-layout.mjs";
import { CHECKS, checkTag, loadValidator } from "./lib/haxschema.mjs";
import {
  baselineGrowth,
  baselineSize,
  compareToBaseline,
  shrinkBaseline,
  sortBaseline,
} from "./lib/gate-baseline.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const BASELINE_REL = "scripts/haxschema.baseline.json";
const BASELINE = path.join(root, BASELINE_REL);
const LIST_LIMIT = 12;
// changes to the check itself re-check every tag
const TOOLING = [
  /^scripts\/haxschema/,
  /^scripts\/lib\/haxschema\.mjs$/,
  /^scripts\/lib\/haxProperties\.schema\.json$/,
  /^scripts\/lib\/gate-baseline\.mjs$/,
  /^scripts\/api-snapshot\.mjs$/,
  /^hax-elements-registry\.json$/,
  /^\.github\/workflows\/haxschema\.yml$/,
];

const argv = process.argv.slice(2);
const flag = (name) => argv.includes(name);
const option = (name) => {
  const i = argv.indexOf(name);
  return i !== -1 && argv[i + 1] && !argv[i + 1].startsWith("--")
    ? argv[i + 1]
    : null;
};

function git(args) {
  try {
    return execFileSync("git", args, {
      cwd: root,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    });
  } catch {
    return null;
  }
}

function findBase() {
  return ["origin/HEAD", "origin/master", "origin/main"].find(
    (ref) => git(["rev-parse", "--verify", "--quiet", ref]) !== null,
  );
}

function parseBaseline(text) {
  try {
    return JSON.parse(text).tags || {};
  } catch {
    return {};
  }
}

function readBaseline() {
  try {
    return parseBaseline(fs.readFileSync(BASELINE, "utf8"));
  } catch {
    return {};
  }
}

function writeBaseline(tags) {
  const data = {
    about:
      "Known HAXSchema problems in authorable elements: tag -> check -> finding -> count. Shrink-only: generated by yarn test:haxschema --update-baseline, which only removes entries. See CONTRIBUTING.md (HAXSchema check).",
    tags: sortBaseline(tags),
  };
  fs.writeFileSync(BASELINE, JSON.stringify(data, null, 2) + "\n");
}

/** the element folders a tag's class and schema live in */
function foldersOf(facts) {
  const out = new Set([facts.folder]);
  const m = String(facts.from || "").match(/^elements\/([^/]+)\//);
  if (m) {
    out.add(m[1]);
  }
  return out;
}

function selectTags(facts) {
  const all = Object.keys(facts).sort();
  const wanted = option("--tags");
  if (wanted) {
    const want = new Set(wanted.split(",").map((t) => t.trim()));
    return {
      picked: all.filter((t) => want.has(t)),
      why: `--tags (${want.size})`,
    };
  }
  if (flag("--all")) {
    return { picked: all, why: "all authorable tags" };
  }
  const base = option("--base") || findBase();
  const files = changedFiles(root, base);
  if (files.some((f) => TOOLING.some((re) => re.test(f)))) {
    return { picked: all, why: "the check itself changed: all tags" };
  }
  const folders = changedFolders(files);
  return {
    picked: all.filter((t) =>
      [...foldersOf(facts[t])].some((f) => folders.has(f)),
    ),
    why: `element folders changed vs ${base || "local changes"}: ${[...folders].sort().join(", ") || "none"}`,
  };
}

function checkBaselineShrinkOnly(ref) {
  const before = git(["show", `${ref}:${BASELINE_REL}`]);
  if (before === null) {
    console.log(
      `haxschema: no ${BASELINE_REL} at ${ref}; nothing to compare (first baseline).`,
    );
    return 0;
  }
  const grown = baselineGrowth(parseBaseline(before), readBaseline());
  if (!grown.length) {
    console.log(
      `haxschema: ${BASELINE_REL} did not grow compared with ${ref}.`,
    );
    return 0;
  }
  console.log(
    `\n${BASELINE_REL} grew compared with ${ref} (${grown.length} entr${grown.length === 1 ? "y" : "ies"}). The baseline only shrinks: fix the HAXSchema instead.`,
  );
  grown
    .slice(0, 40)
    .forEach((g) =>
      console.log(
        `  ${g.element}  ${g.group}  ${g.key}  (${g.baseline} -> ${g.count})`,
      ),
    );
  return 1;
}

function line(out, text) {
  console.log(text);
  out.push(text);
}

function listItems(out, items) {
  const by = {};
  for (const i of items) {
    (by[`<${i.element}>  ${i.group}`] =
      by[`<${i.element}>  ${i.group}`] || []).push(i);
  }
  for (const head of Object.keys(by)) {
    line(out, `  ${head}`);
    by[head]
      .slice(0, LIST_LIMIT)
      .forEach((i) =>
        line(
          out,
          `      ${i.key}${i.count > 1 || i.baseline ? `  (${i.count}${i.baseline ? `, baseline ${i.baseline}` : ""})` : ""}`,
        ),
      );
    if (by[head].length > LIST_LIMIT) {
      line(out, `      ...and ${by[head].length - LIST_LIMIT} more`);
    }
  }
}

async function main() {
  const shrinkRef = option("--check-baseline");
  if (shrinkRef) {
    return checkBaselineShrinkOnly(shrinkRef);
  }
  const cem = await loadAnalyzer();
  if (!cem) {
    throw new Error(
      "@custom-elements-manifest/analyzer is not installed: run yarn install",
    );
  }
  const validate = loadValidator();
  const t0 = Date.now();
  const { facts } = buildSnapshot(root, cem);
  const { picked, why } = selectTags(facts);
  console.log(
    `haxschema: analyzed ${Object.keys(facts).length} authorable tags in ${((Date.now() - t0) / 1000).toFixed(1)}s; ${why}`,
  );
  if (!picked.length) {
    console.log("haxschema: no authorable tags to check.");
    return 0;
  }
  const results = {};
  for (const tag of picked) {
    results[tag] = checkTag(tag, facts[tag], validate);
  }
  const baseline = readBaseline();

  if (flag("--update-baseline")) {
    const allow = flag("--allow-additions");
    const next = shrinkBaseline(baseline, results, { allowAdditions: allow });
    writeBaseline(next);
    console.log(
      `haxschema: baseline ${baselineSize(baseline)} -> ${baselineSize(next)} finding(s) for ${picked.length} tag(s)${allow ? `, ${baselineGrowth(baseline, next).length} added (--allow-additions)` : " (only removes; --allow-additions only adds)"}.`,
    );
    return 0;
  }

  const { fresh, known, fixed } = compareToBaseline(results, baseline);
  const out = [];
  if (known.length) {
    line(
      out,
      `\nAdvisory: ${known.reduce((n, k) => n + k.count, 0)} baselined HAXSchema problem(s) in the checked tags (work these down):`,
    );
    listItems(out, known);
  }
  if (fixed.length) {
    const names = [...new Set(fixed.map((f) => f.element))].join(",");
    line(
      out,
      `\nFixed since the baseline (run yarn test:haxschema --update-baseline --tags ${names} and commit the smaller baseline):`,
    );
    listItems(out, fixed);
  }
  if (fresh.length) {
    line(out, `\nNEW HAXSchema problems:`);
    listItems(out, fresh);
    const groups = [...new Set(fresh.map((f) => f.group))];
    groups.forEach((g) => line(out, `  ${g}: ${CHECKS[g] || g}`));
  }
  line(
    out,
    `\nhaxschema: ${picked.length} tag(s) checked, ${fresh.length} new, ${known.length} baselined, ${fixed.length} fixed.`,
  );
  if (process.env.GITHUB_STEP_SUMMARY) {
    try {
      fs.appendFileSync(
        process.env.GITHUB_STEP_SUMMARY,
        `## HAXSchema\n\n\`\`\`\n${out.join("\n").trim()}\n\`\`\`\n`,
      );
    } catch {
      // the summary is a convenience
    }
  }
  return fresh.length ? 1 : 0;
}

main().then(
  (code) => process.exit(code),
  (e) => {
    console.error(`haxschema: ${(e && e.stack) || e}`);
    process.exit(1);
  },
);
